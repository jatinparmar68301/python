#concept of relational operators
j = int(input("Enter value for j=="))
p = int(input("Enter value for p=="))

result = j == p
print(f"{result} = {j}=={p}")

result = j != p
print(f"{result} = {j}!={p}")

result = j > p
print(f"{result} = {j}>{p}")

result = j < p
print(f"{result} = {j}<{p}")

result = j <= p
print(f"{result} = {j}<={p}")

result = j >= p
print(f"{result} = {j}>={p}")
